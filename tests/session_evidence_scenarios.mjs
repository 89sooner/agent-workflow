 await page.getByRole('button',{name:'근거 연결 저장',exact:true}).click();
 const link=panel.getByRole('link',{name:'사용자가 연결한 PR',exact:true});await link.waitFor();
 assert.equal(await link.getAttribute('href'),'https://github.com/example/repo/pull/12');
 await panel.getByRole('button',{name:'근거 연결 해제',exact:true}).click();
