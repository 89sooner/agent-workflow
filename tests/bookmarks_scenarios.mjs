import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {createRequire} from 'node:module';
import {homedir} from 'node:os';
import {join} from 'node:path';
const {chromium}=createRequire(import.meta.url)(process.env.WORKFLOW_PLAYWRIGHT_PATH||join(homedir(),'.cache/webprobe/runtime/node_modules/playwright'));
const f=JSON.parse(await fs.readFile(process.argv[2],'utf8'));
const browser=await chromium.launch({headless:true,args:['--enable-unsafe-swiftshader']});
try{
 const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'}),errors=[],writes=[];
 page.on('pageerror',e=>errors.push(e.message));page.on('request',r=>{if(r.method()!=='GET')writes.push(new URL(r.url()).pathname)});
 await page.goto(f.url+'/sessions');await page.locator('.native-session').filter({hasText:'Claude'}).click();
 await page.waitForSelector('.native-history li');
 const panel=page.getByLabel('세션 북마크');
 await panel.getByText('현재 세션 구간 저장',{exact:true}).click();
 await page.getByLabel('북마크 이름').fill('BROWSER-BOOKMARK');
 await page.getByRole('button',{name:'북마크 저장',exact:true}).click();
 await panel.getByRole('link',{name:'BROWSER-BOOKMARK',exact:true}).waitFor();
 const deepLink=await panel.getByRole('link',{name:'BROWSER-BOOKMARK',exact:true}).getAttribute('href');
 await page.goto(f.url+deepLink);
 await page.getByLabel('세션 북마크').waitFor();
 assert(new URL(page.url()).searchParams.get('bookmark'),'bookmark survives parent URL synchronization');
 await page.getByLabel('북마크 이벤트 구간').waitFor();
 const exportUrl=await panel.getByRole('link',{name:'메타데이터 내보내기'}).getAttribute('href');
 const data=await (await page.request.get(f.url+exportUrl)).json();
 assert.equal(data.bookmark.provider,'claude');assert.equal(data.bookmark.native_id,'claude-pilot');
 assert.equal(data.complete,true);assert.equal(data.events.length,1);
 assert(!JSON.stringify(data).includes('PRIVATE_PROMPT'));
 await fs.writeFile(f.control,'prunehistory');
 await panel.getByText('근거 만료',{exact:false}).waitFor();
 const expired=await (await page.request.get(f.url+exportUrl)).json();assert.equal(expired.complete,false);assert.equal(expired.events.length,0);
 await page.goto(f.url+'/overview');
 const all=page.getByLabel('전체 북마크');await all.getByText('BROWSER-BOOKMARK',{exact:true}).waitFor();
 assert((await all.innerText()).includes('근거 만료'));
 await all.getByRole('button',{name:'북마크 삭제',exact:true}).click();
 await all.getByText('저장된 북마크가 없습니다.',{exact:true}).waitFor();
 assert.deepEqual(errors,[]);assert.deepEqual(writes,['/api/native/bookmarks','/api/native/bookmarks']);
 console.log(JSON.stringify({passed:true,checks:['direct bookmark deep link reload','provenance export','bookmark add/preview/export','metadata-only export','expired source shown','global index preserves expired bookmark','remove expired bookmark','only metadata writes']}));
}finally{await browser.close()}
