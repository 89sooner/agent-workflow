import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {createRequire} from 'node:module';
import {homedir} from 'node:os';
import {join} from 'node:path';
const require = createRequire(import.meta.url);
const {chromium} = require(process.env.WORKFLOW_PLAYWRIGHT_PATH || join(homedir(), '.cache/webprobe/runtime/node_modules/playwright'));
const f = JSON.parse(await fs.readFile(process.argv[2], 'utf8'));
const browser = await chromium.launch({headless:true,args:['--enable-unsafe-swiftshader']});
const page = await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
const errors=[], writes=[];
page.on('pageerror', e=>errors.push(e.message));
page.on('request', r=>{if(r.method()!=='GET') writes.push(new URL(r.url()).pathname);});
const until = async fn => {
  const end=Date.now()+25000;
  while(Date.now()<end){if(await fn()) return; await page.waitForTimeout(100);}
  throw Error('Expected onboarding state did not appear');
};
const command = async value => {
  await fs.writeFile(f.control,value);
  await until(async()=>{try{await fs.access(f.control);return false;}catch{return true;}});
};
const screenshot = async name => {
  if(!process.env.WORKFLOW_SCREENSHOT_DIR) return;
  await fs.mkdir(process.env.WORKFLOW_SCREENSHOT_DIR,{recursive:true});
  await page.screenshot({path:join(process.env.WORKFLOW_SCREENSHOT_DIR,name+'.png'),fullPage:true});
};
try {
  await page.goto(f.url+'/mission');
  await page.getByTestId('onboarding-empty').waitFor();
  assert.equal(await page.getByRole('link',{name:'작업 등록·실행 관리 ↗'}).count(),0);
  await page.getByRole('button',{name:'첫 프로젝트 연결',exact:true}).click();
  await page.getByLabel('프로젝트 폴더 경로').fill(f.project);
  await page.getByText('서버 주소·인증 설정',{exact:true}).click();
  await page.getByLabel('OpenCode 서버 주소').fill(f.opencode);
  await command('auth');
  await page.getByRole('button',{name:'연결하고 관측하기',exact:true}).click();
  await page.getByRole('heading',{name:'인증을 확인해 주세요'}).waitFor();
  assert.match(await page.getByRole('dialog').innerText(),/환경변수/);
  await command('recover');
  await page.getByRole('button',{name:'연결하고 관측하기',exact:true}).click();
  await page.getByRole('dialog').waitFor({state:'hidden'});
  await page.locator('.task-item').filter({hasText:'한글 세션'}).waitFor();
  await page.locator('.task-item').filter({hasText:'한글 세션'}).click();
  await page.locator('.graph-node').filter({hasText:'실제 구현 담당'}).waitFor();
  await screenshot('onboarding-connected');
  await page.getByLabel('작업·담당자 검색',{exact:true}).fill('no-match-search');
  await until(async()=>(await page.getByTestId('task-empty').innerText()).includes('검색 조건'));
  await page.getByRole('button',{name:'검색 조건 초기화'}).click();
  await command('fail');
  await page.getByRole('heading',{name:'서버 연결을 확인해 주세요'}).waitFor({timeout:25000});
  assert.equal(await page.locator('.mission-shell').getAttribute('data-mode'),'paused');
  assert.match(await page.locator('.notice.error').innerText(),/마지막 성공/);
  await command('recover');
  await page.getByRole('button',{name:'다시 연결',exact:true}).click();
  await until(async()=>!await page.locator('.notice.error').count());
  await page.getByRole('button',{name:/프로젝트 전체 관제실/}).click();
  await command('empty');
  await page.getByTestId('no-sessions').waitFor({timeout:25000});
  await command('new');
  await page.locator('.task-item').filter({hasText:'자동 발견된 새 세션'}).waitFor({timeout:25000});
  await page.getByRole('button',{name:'프로젝트 연결',exact:true}).click();
  await page.getByLabel('사용 도구').selectOption('codex');
  await page.getByRole('button',{name:'프로젝트 기록 찾기'}).click();
  await page.locator('dialog .candidate-option input').check();
  await page.getByRole('button',{name:'연결하고 관측하기',exact:true}).click();
  await page.locator('.task-item').filter({hasText:'UI-WORKFLOW'}).waitFor();
  assert.equal(await page.getByRole('link',{name:'작업 등록·실행 관리 ↗'}).count(),0);
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'프로젝트 연결',exact:true}).click();
  await screenshot('onboarding-mobile');
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  assert.equal(await page.getByRole('dialog').evaluate(el=>el.scrollWidth<=el.clientWidth),true);
  await page.keyboard.press('Escape');
  await page.getByRole('dialog').waitFor({state:'hidden'});
  assert.equal(await page.getByRole('button',{name:'프로젝트 연결',exact:true}).evaluate(el=>el===document.activeElement),true);
  await page.goto(f.readonly+'/mission');
  await page.getByRole('button',{name:'프로젝트 연결',exact:true}).click();
  await page.getByRole('heading',{name:'이 관제실은 읽기 전용입니다'}).waitFor();
  assert.equal(await page.getByRole('button',{name:'연결하고 관측하기'}).count(),0);
  assert.equal(await page.getByRole('link',{name:'작업 등록·실행 관리 ↗'}).count(),0);
  await page.goto(f.manager+'/mission');
  await page.getByRole('link',{name:'작업 등록·실행 관리 ↗'}).waitFor();
  assert.deepEqual(errors,[]);
  assert.ok(writes.length>=4);
  assert.ok(writes.every(path=>['/api/connections/connect','/api/connections/discover'].includes(path)),JSON.stringify(writes));
  console.log('PASS empty installation, UI OpenCode connect, auth failure/recovery, automatic sessions, search reset, empty sessions, disconnect recovery, workflow candidate selection, permissions, keyboard, 390px, no execution writes');
} finally { await browser.close(); }
