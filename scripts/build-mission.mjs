import { build, context } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const options = {
  absWorkingDir: root,
  entryPoints: ["frontend/mission/main.tsx"],
  outfile: "agent_workflow/static/mission.js",
  bundle: true,
  format: "esm",
  platform: "browser",
  target: ["es2022"],
  minify: true,
  legalComments: "inline",
  define: { "process.env.NODE_ENV": '"production"' },
  banner: {
    js: "// Generated by npm run build:mission. Runtime licenses: /static/MISSION_LICENSES.txt",
  },
};
const packages = [
  "react",
  "react-dom",
  "scheduler",
  "@react-three/fiber",
  "react-use-measure",
  "its-fine",
  "zustand",
  "suspend-react",
  "use-sync-external-store",
  "three",
];
const licenses = (
  await Promise.all(
    packages.map(async (name) => {
      const pkg = JSON.parse(
        await readFile(
          resolve(root, "node_modules", name, "package.json"),
          "utf8",
        ),
      );
      let license =
        name === "@react-three/fiber"
          ? await readFile(
              resolve(root, "frontend/licenses/react-three-fiber-LICENSE.txt"),
              "utf8",
            )
          : undefined;
      for (const file of ["LICENSE", "LICENSE.md", "LICENSE.txt"]) {
        try {
          license = await readFile(
            resolve(root, "node_modules", name, file),
            "utf8",
          );
          break;
        } catch {}
      }
      if (!license) throw Error(`Missing license: ${name}`);
      return `${name} ${pkg.version}\n${license.replaceAll("\r\n", "\n")}`;
    }),
  )
).join("\n\n------------------------------\n\n");
const licensePath = resolve(root, "agent_workflow/static/MISSION_LICENSES.txt");
if (process.argv.includes("--watch")) {
  await writeFile(licensePath, licenses);
  const c = await context(options);
  await c.watch();
  console.log(
    "Watching React mission control. Run a separate read-only Python preview.",
  );
} else if (process.argv.includes("--check")) {
  const result = await build({ ...options, write: false });
  for (const file of result.outputFiles) {
    if ((await readFile(file.path, "utf8")).replaceAll("\r\n", "\n") !== file.text)
      throw Error(`Stale mission asset: ${file.path}`);
  }
  if ((await readFile(licensePath, "utf8")).replaceAll("\r\n", "\n") !== licenses)
    throw Error("Stale mission licenses");
  console.log("Mission assets and runtime licenses match their pinned source.");
} else {
  await build(options);
  await writeFile(licensePath, licenses);
  console.log("Built React mission control and runtime licenses.");
}
