import { build, context } from 'esbuild';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const output = resolve(root, 'agent_workflow/static/three-vendor.js');
const options = {
  absWorkingDir: root,
  entryPoints: ['frontend/vendor-entry.js'],
  outfile: output,
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: ['es2020'],
  minify: true,
  legalComments: 'inline',
  sourcemap: false,
  banner: { js: '// Generated by npm run build. Three.js 0.187.0 (MIT); see THIRD_PARTY_LICENSES.md.' },
};
if (process.argv.includes('--watch')) {
  const watcher = await context(options);
  await watcher.watch();
  console.log('Watching the local Three.js vendor entry. Run the Python server separately.');
} else if (process.argv.includes('--check')) {
  const result = await build({ ...options, write: false });
  const committed = await readFile(output, 'utf8');
  if (committed !== result.outputFiles[0].text) {
    console.error('The committed vendor bundle differs from npm run build.');
    process.exitCode = 1;
  } else console.log('The committed vendor bundle matches the pinned source.');
} else {
  await mkdir(dirname(output), { recursive: true });
  await build(options);
  // Both files ship with the wheel; no npm install is needed by end users.
  const license = await readFile(resolve(root, 'node_modules/three/LICENSE'), 'utf8');
  await writeFile(resolve(root, 'agent_workflow/static/THREE_LICENSE.txt'), license);
  console.log('Built the local Three.js bundle and license.');
}
